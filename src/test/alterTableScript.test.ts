import test from 'node:test';
import assert from 'node:assert/strict';
import { tokenize } from '../repositoryScanner';
import { compareTables, parseConstraint, parseCreateIndex, parseCreateTable, tableModels, type IndexModel, type TableModel } from '../ddlCompare';
import { alterTableScript, columnDefinition } from '../alterTableScript';

const toks = (s: string) => tokenize(s);
const NOW = new Date('2026-11-19T12:00:00Z');

/** The database side as the comparison reads it: catalog columns, pg_get_constraintdef, pg_get_indexdef. */
function dbTable(columns: TableModel['columns'], constraints: Array<[string, string]> = [], indexes: string[] = []): TableModel {
    return {
        columns,
        constraints: constraints.map(([name, def]) => ({ ...parseConstraint(toks(def))!, name })),
        indexes: indexes.map(def => { const { table: _t, ...m } = parseCreateIndex(toks(def))!; return m as IndexModel; }),
        partial: false,
        opaque: false
    };
}
const col = (name: string, type: string, notNull = false, def: string | null = null) => ({ name, type, notNull, default: def });

/** The statements of a script, without its comment lines. */
const statementsOf = (script: string) => script.split('\n').filter(l => l && !l.startsWith('--'));

test('a column missing in the database is added as the repository writes it, casts and type spelling included', () => {
    const repo = parseCreateTable(toks(`CREATE TABLE app.t (
        id integer PRIMARY KEY,
        created date DEFAULT now()::date NOT NULL,
        code VARCHAR(20) COLLATE "C",
        seq integer GENERATED BY DEFAULT AS IDENTITY
    )`));
    const db = dbTable([col('id', 'integer', true)], [['t_pkey', 'PRIMARY KEY (id)']]);
    assert.deepEqual(statementsOf(alterTableScript({ schema: 'app', table: 't', repo, db, now: NOW })), [
        'ALTER TABLE app.t ADD COLUMN created date DEFAULT now()::date NOT NULL;',
        'ALTER TABLE app.t ADD COLUMN code VARCHAR(20) COLLATE "C";',
        'ALTER TABLE app.t ADD COLUMN seq integer GENERATED BY DEFAULT AS IDENTITY;'
    ]);
    assert.equal(columnDefinition(repo.columns[0]), 'id integer NOT NULL');
});

test('a NOT NULL column without a default is added with a warning that it fails on a table with rows', () => {
    const repo = parseCreateTable(toks('CREATE TABLE app.t (id integer, state text NOT NULL)'));
    const script = alterTableScript({ schema: 'app', table: 't', repo, db: dbTable([col('id', 'integer')]), now: NOW });
    assert.match(script, /-- NOT NULL without a default fails while app\.t has rows[^\n]*\nALTER TABLE app\.t ADD COLUMN state text NOT NULL;/);
});

test('a changed column gets its type, default and NOT NULL from the repository; a column only the database has is dropped', () => {
    const repo = parseCreateTable(toks("CREATE TABLE app.t (id integer, amount numeric(12,2) DEFAULT 0 NOT NULL, state varchar(1))"));
    const db = dbTable([col('id', 'integer'), col('amount', 'numeric(10,2)', false, "'1'"), col('state', 'character varying(1)', true, "'n'"), col('legacy', 'text')]);
    assert.deepEqual(statementsOf(alterTableScript({ schema: 'app', table: 't', repo, db, now: NOW })), [
        'ALTER TABLE app.t ALTER COLUMN amount TYPE numeric(12,2);',
        'ALTER TABLE app.t ALTER COLUMN amount SET DEFAULT 0;',
        'ALTER TABLE app.t ALTER COLUMN amount SET NOT NULL;',
        'ALTER TABLE app.t ALTER COLUMN state DROP DEFAULT;',
        'ALTER TABLE app.t ALTER COLUMN state DROP NOT NULL;',
        'ALTER TABLE app.t DROP COLUMN legacy;'
    ]);
    assert.match(alterTableScript({ schema: 'app', table: 't', repo, db, now: NOW }), /-- Add USING amount::numeric\(12,2\) if the values do not convert by themselves\.\nALTER TABLE app\.t ALTER COLUMN amount TYPE/);
});

test('constraints and indexes are dropped before columns change and added after, in an order that runs', () => {
    const repo = tableModels([
        { type: 'createTable', toks: toks('CREATE TABLE app.t (id integer PRIMARY KEY, other_id integer REFERENCES app.other (id) ON DELETE CASCADE, note text, CONSTRAINT ck_note CHECK (note <> \'\'))') },
        { type: 'createIndex', toks: toks('CREATE INDEX ix_note ON t USING btree (lower(note)) WHERE note IS NOT NULL;') }
    ], 't')[0];
    const db = dbTable(
        [col('id', 'integer', true), col('other_id', 'integer'), col('note', 'text')],
        [['t_pkey', 'PRIMARY KEY (id)'], ['t_other_id_fkey', 'FOREIGN KEY (other_id) REFERENCES app.other(id)'], ['t_note_key', 'UNIQUE (note)']],
        ['CREATE INDEX ix_old ON app.t USING btree (note)']
    );
    assert.deepEqual(statementsOf(alterTableScript({ schema: 'app', table: 't', repo, db, now: NOW })), [
        'ALTER TABLE app.t DROP CONSTRAINT t_other_id_fkey;',
        'ALTER TABLE app.t DROP CONSTRAINT t_note_key;',
        'DROP INDEX app.ix_old;',
        "ALTER TABLE app.t ADD CONSTRAINT ck_note CHECK (note <> '');",
        'ALTER TABLE app.t ADD CONSTRAINT t_other_id_fkey FOREIGN KEY (other_id) REFERENCES app.other (id) ON DELETE CASCADE;',
        'CREATE INDEX ix_note ON app.t USING btree (lower(note)) WHERE note IS NOT NULL;'
    ], 'the foreign key with other actions is dropped and added again; the primary key stays');
});

test('the script follows what the comparison reports: a table that matches gets nothing to run', () => {
    const repo = parseCreateTable(toks('CREATE TABLE app.t (id serial PRIMARY KEY, note text)'));
    const db = dbTable([col('id', 'integer', true, "nextval('app.t_id_seq'::regclass)"), col('note', 'text')], [['t_pkey', 'PRIMARY KEY (id)']]);
    assert.deepEqual(compareTables(repo, db), []);
    const script = alterTableScript({ schema: 'app', table: 't', repo, db, now: NOW });
    assert.deepEqual(statementsOf(script), []);
    assert.match(script, /-- Nothing to change: the table matches the repository\./);
});

test('names that need quotes are quoted, and the table is always written with its schema', () => {
    const repo = parseCreateTable(toks('CREATE TABLE "Sales"."Order" ("Id" integer, "user" text, "order" integer)'));
    const db = dbTable([col('Id', 'integer'), col('Old Name', 'text')]);
    assert.deepEqual(statementsOf(alterTableScript({ schema: 'Sales', table: 'Order', repo, db, now: NOW })), [
        'ALTER TABLE "Sales"."Order" ADD COLUMN "user" text;',
        'ALTER TABLE "Sales"."Order" ADD COLUMN "order" integer;',
        'ALTER TABLE "Sales"."Order" DROP COLUMN "Old Name";'
    ]);
});

test('a table with INHERITS or LIKE drops no columns, as the comparison does not count them as missing', () => {
    const repo = parseCreateTable(toks('CREATE TABLE app.t (id integer) INHERITS (app.base)'));
    const script = alterTableScript({ schema: 'app', table: 't', repo, db: dbTable([col('id', 'integer'), col('base_col', 'text')]), now: NOW });
    assert.doesNotMatch(script, /DROP COLUMN/);
});

test('what ALTER TABLE cannot do is said in comments, and the header says nothing has run', () => {
    const repo = parseCreateTable(toks('CREATE TABLE app.t (a integer GENERATED ALWAYS AS IDENTITY, b text, c text)'));
    const db = dbTable([col('a', 'integer'), col('c', 'text'), col('b', 'text')]);
    const script = alterTableScript({ schema: 'app', table: 't', repo, db, columnOrder: true, searchPath: ['app', 'public'], now: NOW });
    assert.match(script, /^-- ALTER TABLE script for app\.t: [^\n]*\n-- Generated by Compare Repository with Database on 2026-11-19T12:00:00\.000Z\.\n-- Nothing has been run\./);
    assert.match(script, /\nSET search_path TO app, public;\n/, 'the names inside the definitions resolve as in the repository\'s file');
    assert.match(script, /-- Not written as statements:\n-- Column a: default identity in the repository, none in the database; identity and generated columns are changed by hand\./);
    assert.match(script, /-- The columns are in another order in the database \(a, c, b\); ALTER TABLE cannot reorder them\./);
    assert.doesNotMatch(script, /ALTER COLUMN a /, 'NOT NULL of an identity column is not touched either');
});
