const toks = (sql: string) => tokenize(sql);

// ===== normalisation =====

test('normalizeExpression makes the database spelling and the repository spelling of an expression the same', () => {
    const pairs: Array<[string, string]> = [
        ["('J'::character varying)", "'J'"],
        ["nextval('leda.seq_x'::regclass)", "nextval('seq_x')"],
        ['CAST(NULL AS timestamp)', 'NULL'],
        ["(now() - '3 mons'::interval)", "now() - interval '3 months'"],
        ["(CURRENT_DATE + '7 days'::interval)", "current_date + interval '1 week'"],
        ['oracle.sysdate()', 'sysdate()'],
        ['((a)::text || (b)::text)', 'a || b']
    ];
    for (const [db, repo] of pairs) assert.equal(normalizeExpression(db), normalizeExpression(repo), `${db} vs ${repo}`);
    assert.notEqual(normalizeExpression("'J'"), normalizeExpression("'N'"));
});

test('interval literals are written the way PostgreSQL prints them', () => {
    assert.equal(normalizeIntervalLiteral('3 months'), '3 mons');
    assert.equal(normalizeIntervalLiteral('1 MONTH'), '1 mon');
    assert.equal(normalizeIntervalLiteral('1 day'), '1 day');
    assert.equal(normalizeIntervalLiteral('2 weeks'), '14 days');
    assert.equal(normalizeIntervalLiteral('2 hours'), '02:00:00');
    assert.equal(normalizeIntervalLiteral('-1 year'), '-1 year');
    assert.equal(normalizeIntervalLiteral('1 day 2 hours'), null, 'only a single unit is rewritten');
    assert.equal(normalizeIntervalLiteral('J'), null);
});

test('columnType keeps the modifiers and maps aliases and serials', () => {
    assert.equal(columnType('VARCHAR(20)'), 'character varying(20)');
    assert.equal(columnType('character varying(20)'), 'character varying(20)');
    assert.equal(columnType('numeric(10)'), 'numeric(10,0)');
    assert.equal(columnType('char'), 'character(1)');
    assert.equal(columnType('int4'), 'integer');
    assert.equal(columnType('bigserial'), 'bigint');
    assert.equal(columnType('varchar(10)[]'), 'character varying(10)[]');
    assert.notEqual(columnType('varchar(20)'), columnType('varchar(30)'));
});

// ===== constraints, indexes, tables =====

test('constraints are read from a table definition and from pg_get_constraintdef alike', () => {
    // The text as written differs by nature; what is compared is the rest.
    const shape = (c: ReturnType<typeof parseConstraint>) => { const { sql: _sql, ...rest } = c!; return rest; };
    const repo = shape(parseConstraint(toks('CONSTRAINT fk_x FOREIGN KEY (a, b) REFERENCES app.other (x, y) ON DELETE CASCADE')));
    const db = shape(parseConstraint(toks('FOREIGN KEY (a, b) REFERENCES app.other(x, y) ON DELETE CASCADE')));
    assert.deepEqual(repo, { kind: 'foreign', name: 'fk_x', columns: ['a', 'b'], refTable: 'other', refColumns: ['x', 'y'], onDelete: 'cascade', onUpdate: 'no action' });
    assert.deepEqual({ ...db, name: 'fk_x' }, repo);
    assert.deepEqual(shape(parseConstraint(toks('CHECK ((amount > (0)::numeric))'))), { kind: 'check', name: undefined, columns: [], expression: 'amount > 0' });
    assert.deepEqual(shape(parseConstraint(toks('UNIQUE NULLS NOT DISTINCT (a)'))), { kind: 'unique', name: undefined, columns: ['a'] });
});

test('indexes are read from CREATE INDEX and from pg_get_indexdef alike, defaults dropped', () => {
    const repo = parseCreateIndex(toks('CREATE UNIQUE INDEX IF NOT EXISTS ix_a ON app.t (a ASC, lower(b)) WHERE c IS NULL'));
    const db = parseCreateIndex(toks('CREATE UNIQUE INDEX ix_a ON app.t USING btree (a, lower((b)::text)) WHERE (c IS NULL)'));
    assert.ok(repo && db);
    assert.deepEqual({ ...repo, table: null, sql: null }, { ...db, table: null, sql: null });
    assert.deepEqual(repo.keys, ['a', 'lower b']);
    assert.equal(parseCreateIndex(toks('CREATE INDEX ON t (a DESC NULLS FIRST)'))?.keys[0], 'a desc');
    assert.equal(parseCreateIndex(toks('CREATE INDEX ON t (a)'))?.name, 't_a_idx', 'an unnamed index gets the name PostgreSQL gives it');
});

test('a CREATE TABLE gives its columns with types, NOT NULL and defaults, and its constraints', () => {
    const model = parseCreateTable(toks(`CREATE TABLE app.orders (
        id bigserial PRIMARY KEY,
        state varchar(1) DEFAULT 'N' NOT NULL CHECK (state IN ('N', 'D')),
        customer_id integer REFERENCES app.customers ON DELETE SET NULL,
        note text DEFAULT NULL,
        seq integer GENERATED BY DEFAULT AS IDENTITY,
        total numeric(10,2) GENERATED ALWAYS AS (1 + 1) STORED,
        CONSTRAINT uq_state UNIQUE (state, customer_id)
    )`));
    assert.deepEqual(model.columns.map(c => [c.name, c.type, c.notNull, c.default]), [
        ['id', 'bigint', true, null],
        ['state', 'character varying(1)', true, "'N'"],
        ['customer_id', 'integer', false, null],
        ['note', 'text', false, null],
        ['seq', 'integer', true, 'identity'],
        ['total', 'numeric(10,2)', false, 'generated 1 + 1']
    ]);
    assert.deepEqual(model.constraints.map(c => [c.kind, c.name, c.columns.join(',')]), [
        ['primary', 'orders_pkey', 'id'],
        ['check', 'orders_state_check', 'state'],
        ['foreign', 'orders_customer_id_fkey', 'customer_id'],
        ['unique', 'uq_state', 'state,customer_id']
    ]);
    assert.equal(model.constraints[2].onDelete, 'set null');
    assert.equal(parseCreateTable(toks('CREATE TABLE p1 PARTITION OF p FOR VALUES IN (1)')).opaque, true);
    assert.equal(parseCreateTable(toks('CREATE TABLE c (a int) INHERITS (p)')).partial, true);
});

test('the later ALTER TABLE, CREATE INDEX and DROP INDEX of a table are folded into its model, up to the next CREATE TABLE', () => {
    const models = tableModels([
        { type: 'createTable', toks: toks('CREATE TABLE t (a int, b text, c int)') },
        { type: 'alterTable', toks: toks('ALTER TABLE t ADD COLUMN d date NOT NULL, DROP COLUMN c, ALTER COLUMN b TYPE varchar(10), ALTER COLUMN a SET DEFAULT 0') },
        { type: 'alterTable', toks: toks('ALTER TABLE ONLY t ADD CONSTRAINT t_pk PRIMARY KEY (a)') },
        { type: 'alterTable', toks: toks('ALTER TABLE t RENAME COLUMN d TO e') },
        { type: 'createIndex', toks: toks('CREATE INDEX ix_b ON t (b)') },
        { type: 'createIndex', toks: toks('CREATE INDEX ix_gone ON t (a)') },
        { type: 'dropIndex', name: 'ix_gone' },
        { type: 'createTable', toks: toks('CREATE TABLE t (a int)') }
    ], 't');
    assert.equal(models.length, 2);
    const [first, second] = models;
    assert.deepEqual(first.columns.map(c => [c.name, c.type, c.notNull, c.default]), [
        ['a', 'integer', true, '0'], ['b', 'character varying(10)', false, null], ['e', 'date', true, null]
    ]);
    assert.deepEqual(first.constraints.map(c => c.name), ['t_pk']);
    assert.deepEqual(first.indexes.map(i => i.name), ['ix_b']);
    assert.deepEqual(second.columns.map(c => c.name), ['a']);
});

const dbTable = (over: Partial<TableModel> = {}): TableModel => ({
    columns: [
        { name: 'id', type: 'bigint', notNull: true, default: "nextval 'orders_id_seq'" },
        { name: 'state', type: 'character varying(1)', notNull: true, default: "'N'" }
    ],
    constraints: [{ kind: 'primary', name: 'orders_pkey', columns: ['id'] }],
    indexes: [{ name: 'ix_state', unique: false, method: 'btree', keys: ['state'] }],
    partial: false,
    opaque: false,
    ...over
});

test('a table equal on both sides has no differences, a serial matches its nextval default', () => {
    const [repo] = tableModels([
        { type: 'createTable', toks: toks("CREATE TABLE orders (id bigserial PRIMARY KEY, state varchar(1) NOT NULL DEFAULT 'N')") },
        { type: 'createIndex', toks: toks('CREATE INDEX ix_state ON orders (state)') }
    ], 'orders');
    assert.deepEqual(compareTables(repo, dbTable()), []);
});

test('compareTables reports columns, types, NOT NULL, defaults, constraints and indexes on either side', () => {
    const [repo] = tableModels([
        { type: 'createTable', toks: toks("CREATE TABLE orders (id bigint PRIMARY KEY, state varchar(2) DEFAULT 'X', extra int)") },
        { type: 'createIndex', toks: toks('CREATE UNIQUE INDEX ix_extra ON orders (extra)') }
    ], 'orders');
    const found = compareTables(repo, dbTable()).map(d => `${d.path}: ${d.message}`);
    assert.deepEqual(found, [
        "column id: default none in the repository, nextval 'orders_id_seq' in the database",
        'column state: type character varying(2) in the repository, character varying(1) in the database',
        'column state: NOT NULL in the database only',
        "column state: default 'X' in the repository, 'N' in the database",
        'column extra: missing in the database',
        'index ix_extra: unique btree(extra) is missing in the database',
        'index ix_state: btree(state) is missing in the repository'
    ]);
});

test('the column order counts only when asked for; a partial model ignores columns only the database has', () => {
    const [repo] = tableModels([{ type: 'createTable', toks: toks("CREATE TABLE orders (state varchar(1) NOT NULL DEFAULT 'N', id bigserial PRIMARY KEY)") }], 'orders');
    const db = dbTable({ indexes: [] });
    assert.deepEqual(compareTables(repo, db), []);
    assert.deepEqual(compareTables(repo, db, { columnOrder: true }).map(d => d.message), ['the columns are in another order']);
    const [partial] = tableModels([{ type: 'createTable', toks: toks('CREATE TABLE orders (id bigserial PRIMARY KEY) INHERITS (base)') }], 'orders');
    assert.deepEqual(compareTables(partial, db), []);
});

// ===== types, sequences, triggers =====

test('enums follow ALTER TYPE ADD VALUE with BEFORE and AFTER; the order counts', () => {
    let model = parseCreateType(toks("CREATE TYPE app.mood AS ENUM ('sad', 'happy')"));
    model = applyAlterType(model, toks("ALTER TYPE app.mood ADD VALUE 'ok' BEFORE 'happy'"));
    model = applyAlterType(model, toks("ALTER TYPE app.mood ADD VALUE IF NOT EXISTS 'great' AFTER 'happy'"));
    model = applyAlterType(model, toks("ALTER TYPE app.mood ADD VALUE IF NOT EXISTS 'ok'"));
    assert.deepEqual(model, { flavour: 'enum', labels: ['sad', 'ok', 'happy', 'great'] });
    assert.deepEqual(compareTypes(model, { flavour: 'enum', labels: ['sad', 'ok', 'happy', 'great'] }), []);
    assert.deepEqual(compareTypes(model, { flavour: 'enum', labels: ['ok', 'sad', 'happy', 'great'] }).map(d => d.path), ['values']);
});

test('composite types and domains are compared attribute by attribute and part by part', () => {
    let composite = parseCreateType(toks('CREATE TYPE app.addr AS (street varchar(50), zip int)'));
    composite = applyAlterType(composite, toks('ALTER TYPE app.addr ADD ATTRIBUTE city text, DROP ATTRIBUTE zip'));
    assert.deepEqual(compareTypes(composite, { flavour: 'composite', attributes: [{ name: 'street', type: 'character varying(50)' }, { name: 'city', type: 'text' }] }), []);
    assert.deepEqual(compareTypes(composite, { flavour: 'composite', attributes: [{ name: 'street', type: 'text' }] }).map(d => `${d.path}: ${d.message}`), [
        'attribute street: type character varying(50) in the repository, text in the database',
        'attribute city: missing in the database'
    ]);
    const domain = parseCreateType(toks('CREATE DOMAIN app.amount AS numeric(12,2) NOT NULL DEFAULT 0 CHECK (VALUE >= 0)'));
    assert.deepEqual(domain, { flavour: 'domain', base: 'numeric(12,2)', notNull: true, default: '0', checks: ['value >= 0'] });
    assert.deepEqual(compareTypes(domain, { flavour: 'domain', base: 'numeric(12,2)', notNull: true, default: '0', checks: [normalizeExpression('(VALUE >= (0)::numeric)')] }), []);
});

test('a sequence is compared with PostgreSQL defaults filled in, ALTER SEQUENCE folded in', () => {
    const create = toks('CREATE SEQUENCE app.s INCREMENT BY 10 START WITH 100 CACHE 20');
    const options = [parseSequenceOptions(create, 5), parseSequenceOptions(toks('ALTER SEQUENCE app.s NO CYCLE MAXVALUE 5000'), 5)];
    const model = sequenceModel(options);
    assert.deepEqual(model, { type: 'bigint', increment: '10', min: '1', max: '5000', start: '100', cache: '20', cycle: false });
    assert.deepEqual(compareSequences(model, { ...model }), []);
    assert.deepEqual(compareSequences(model, { ...model, type: 'integer' }).map(d => d.path), ['type']);
    assert.equal(sequenceModel([parseSequenceOptions(toks('CREATE SEQUENCE s AS integer INCREMENT -1'), 3)]).min, '-2147483648');
});

test('triggers are read from CREATE TRIGGER and from pg_get_triggerdef alike', () => {
    const repo = parseCreateTrigger(toks('CREATE OR REPLACE TRIGGER trg AFTER UPDATE OF b, a OR INSERT ON app.t FOR EACH ROW WHEN (NEW.a IS NOT NULL) EXECUTE FUNCTION app.f(\'x\')'));
    const db = parseCreateTrigger(toks("CREATE TRIGGER trg AFTER INSERT OR UPDATE OF a, b ON app.t FOR EACH ROW WHEN ((new.a IS NOT NULL)) EXECUTE FUNCTION app.f('x')"));
    assert.ok(repo && db);
    assert.deepEqual(compareTriggers(repo, db), []);
    assert.deepEqual(repo.events, ['insert', 'update of a,b']);
    assert.deepEqual(compareTriggers(repo, { ...db, level: 'statement' }).map(d => d.path), ['level']);
});

// ===== routines =====

test('signatures are compared by name, mode, type and default; the result type too', () => {
    const p = (name: string, type: string, defaultValue: string | null = null, mode: 'in' | 'out' = 'in') =>
        ({ name, mode, type, defaultValue, start: { line: 0, character: 0 }, end: { line: 0, character: 0 } });
    assert.deepEqual(compareSignatures(
        { params: [p('p_a', 'int4'), p('p_b', 'varchar', "'x'")], returns: 'SETOF varchar' },
        { params: [p('p_a', 'integer'), p('p_b', 'character varying', "'x'::character varying")], returns: 'SETOF character varying' }
    ), []);
    assert.deepEqual(compareSignatures(
        { params: [p('p_a', 'integer', '1')], returns: 'integer' },
        { params: [p('p_x', 'integer', '2'), p('p_y', 'text')], returns: 'numeric' }
    ).map(d => `${d.path}: ${d.message}`), [
        'parameter 1 p_a: named p_a in the repository, p_x in the database',
        'parameter 1 p_a: default 1 in the repository, 2 in the database',
        'parameter 2 p_y: missing in the repository',
        'result: integer in the repository, numeric in the database'
    ]);
    assert.equal(normalizeReturns('TABLE(a int, b varchar)'), normalizeReturns('TABLE(a integer, b character varying)'));
});

// ===== views =====

test('viewQuery takes the query out of CREATE VIEW, with its column list and without its options', () => {
    assert.deepEqual(viewQuery('CREATE OR REPLACE VIEW app.v (x, y) AS SELECT 1, 2 WITH LOCAL CHECK OPTION'), { columns: '(x, y)', query: 'SELECT 1, 2' });
    assert.deepEqual(viewQuery('CREATE MATERIALIZED VIEW IF NOT EXISTS app.mv WITH (fillfactor = 70) AS SELECT a FROM t WITH NO DATA'), { columns: null, query: 'SELECT a FROM t' });
});

test('view definitions are the same apart from white space and parentheses', () => {
    assert.equal(sameViewDefinition(' SELECT a\n   FROM t\n  WHERE ((a > 1) AND ((b < 2) AND (c = 3)));', 'SELECT a FROM t WHERE ((a > 1) AND (b < 2) AND (c = 3));'), true);
    assert.equal(sameViewDefinition('SELECT a FROM t', 'SELECT b FROM t'), false);
});

// ===== scanStructure =====

test('scanStructure finds the statements that shape tables, views, types, sequences and triggers, also in DO blocks', () => {
    const found = scanStructure([
        'SET search_path = app;',
        'CREATE TABLE t (a int);',
        'CREATE UNIQUE INDEX ix ON t (a);',
        'ALTER TABLE IF EXISTS ONLY t ADD COLUMN b int;',
        'DROP INDEX CONCURRENTLY IF EXISTS app.ix_old;',
        'CREATE OR REPLACE VIEW v AS SELECT a FROM t;',
        'CREATE TEMP TABLE scratch (x int);',
        "DO $$ BEGIN CREATE TYPE mood AS ENUM ('a'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;",
        "ALTER TYPE mood ADD VALUE 'b';",
        'CREATE SEQUENCE s;',
        'CREATE TRIGGER trg AFTER INSERT ON t FOR EACH ROW EXECUTE FUNCTION f();',
        'CREATE FUNCTION f() RETURNS trigger LANGUAGE plpgsql AS $f$ BEGIN CREATE TABLE inside (x int); RETURN NEW; END $f$;'
    ].join('\n'));
    assert.deepEqual(found.map(s => `${s.type} ${s.schema ?? '-'}.${s.name}${s.table ? ` on ${s.table.name}` : ''} [${s.searchPath?.join(',') ?? ''}]`), [
        'createTable -.t [app]',
        'createIndex -.ix on t [app]',
        'alterTable -.t [app]',
        'dropIndex app.ix_old [app]',
        'createView -.v [app]',
        'createType -.mood [app]',
        'alterType -.mood [app]',
        'createSequence -.s [app]',
        'createTrigger -.trg on t [app]'
    ]);
    assert.equal(found[0].text, 'CREATE TABLE t (a int)');
});
