/**
 * The ALTER TABLE script that turns a table of the database into what the
 * repository makes of it, from the two models the comparison found
 * different. Pure: it reads no catalog and runs nothing.
 *
 * Definitions are written as the repository writes them — types, defaults,
 * constraints and CREATE INDEX statements —, never in the normalised form the
 * comparison uses. The statements are ordered so the script runs from top
 * to bottom: what goes away is dropped before columns change, and
 * constraints and indexes are added once their columns are there.
 */
import {
    constraintKey,
    defaultsEqual,
    describeConstraint,
    foreignKeysMatch,
    indexKeyOf,
    type ColumnModel,
    type ConstraintModel,
    type TableModel
} from './ddlCompare';
import { qualifiedName, quoteIdentifier } from './ddlGenerator';

export interface AlterTableInput {
    schema: string;
    table: string;
    repo: TableModel;
    db: TableModel;
    /** The search_path the repository's file sets before its CREATE TABLE, for the names inside the definitions. */
    searchPath?: readonly string[] | null;
    /** Mention a different column order, which ALTER TABLE cannot change. */
    columnOrder?: boolean;
    now?: Date;
}

const ADD_ORDER: Record<ConstraintModel['kind'], number> = { primary: 0, unique: 1, check: 2, exclude: 3, foreign: 4 };
const DROP_ORDER: Record<ConstraintModel['kind'], number> = { foreign: 0, check: 1, exclude: 2, unique: 3, primary: 4 };

/** The same constraint on both sides, actions of a foreign key included. */
function sameConstraint(a: ConstraintModel, b: ConstraintModel): boolean {
    if (constraintKey(a) !== constraintKey(b)) return false;
    if (a.kind !== 'foreign') return true;
    return foreignKeysMatch(a, b) && a.onDelete === b.onDelete && a.onUpdate === b.onUpdate;
}

const isComputed = (c: ColumnModel): boolean => c.default === 'identity' || (c.default ?? '').startsWith('generated ');

/** A column as `ADD COLUMN` takes it, from what the repository wrote. */
export function columnDefinition(c: ColumnModel): string {
    const parts = [quoteIdentifier(c.name), c.typeSql || c.type];
    if (c.collateSql) parts.push(c.collateSql);
    if (c.generatedSql) parts.push(c.generatedSql);
    else if (c.defaultSql) parts.push(`DEFAULT ${c.defaultSql}`);
    if (c.notNull && !c.serial && c.default !== 'identity') parts.push('NOT NULL');
    return parts.join(' ');
}

export function alterTableScript(input: AlterTableInput): string {
    const { repo, db } = input;
    const target = qualifiedName(input.schema, input.table);
    const alter = `ALTER TABLE ${target}`;
    const lines = [
        `-- ALTER TABLE script for ${target}: changes the database to what the repository makes of the table.`,
        `-- Generated by Compare Repository with Database on ${(input.now ?? new Date()).toISOString()}.`,
        '-- Nothing has been run. Review it before you run it: DROP statements remove data.',
        ''
    ];
    if (repo.opaque) {
        lines.push('-- The repository creates this table with PARTITION OF, OF or AS SELECT, which the comparison does not take apart; change it by hand.');
        return `${lines.join('\n')}\n`;
    }
    if (input.searchPath && input.searchPath.length > 0) {
        lines.push('-- The search_path the repository\'s file sets, for the names inside the definitions below.');
        lines.push(`SET search_path TO ${input.searchPath.map(quoteIdentifier).join(', ')};`, '');
    }
    const statements: string[] = [];
    const manual: string[] = [];

    // 1. Constraints and indexes the repository does not have, or has otherwise.
    const dropped = db.constraints
        .filter(c => !repo.constraints.some(r => sameConstraint(r, c)))
        .sort((a, b) => DROP_ORDER[a.kind] - DROP_ORDER[b.kind]);
    for (const c of dropped) {
        if (c.name) statements.push(`${alter} DROP CONSTRAINT ${quoteIdentifier(c.name)};`);
        else manual.push(`-- ${describeConstraint(c)} is only in the database, but has no name to drop it by.`);
    }
    for (const index of db.indexes) {
        if (!repo.indexes.some(i => indexKeyOf(i) === indexKeyOf(index))) statements.push(`DROP INDEX ${qualifiedName(input.schema, index.name)};`);
    }

    // 2. Columns: added, changed, dropped.
    for (const c of repo.columns) {
        const other = db.columns.find(x => x.name === c.name);
        const column = `${alter} ALTER COLUMN ${quoteIdentifier(c.name)}`;
        if (!other) {
            if (c.notNull && !c.defaultSql && !c.generatedSql && !c.serial) {
                statements.push(`-- NOT NULL without a default fails while ${target} has rows: fill the column first, or add it without NOT NULL.`);
            }
            statements.push(`${alter} ADD COLUMN ${columnDefinition(c)};`);
            continue;
        }
        if (c.type !== other.type) {
            statements.push(`-- Add USING ${quoteIdentifier(c.name)}::${c.typeSql || c.type} if the values do not convert by themselves.`);
            statements.push(`${column} TYPE ${c.typeSql || c.type};`);
        }
        if (!defaultsEqual(c, other)) {
            if (isComputed(c) || isComputed(other)) {
                manual.push(`-- Column ${c.name}: default ${c.default ?? 'none'} in the repository, ${other.default ?? 'none'} in the database; identity and generated columns are changed by hand.`);
            } else if (c.defaultSql) {
                statements.push(`${column} SET DEFAULT ${c.defaultSql};`);
            } else {
                statements.push(`${column} DROP DEFAULT;`);
            }
        }
        if (c.notNull !== other.notNull && !isComputed(c) && !isComputed(other)) {
            statements.push(`${column} ${c.notNull ? 'SET' : 'DROP'} NOT NULL;`);
        }
    }
    if (!repo.partial) {
        for (const c of db.columns) {
            if (!repo.columns.some(x => x.name === c.name)) statements.push(`${alter} DROP COLUMN ${quoteIdentifier(c.name)};`);
        }
        if (input.columnOrder) {
            const repoOrder = repo.columns.map(c => c.name).filter(n => db.columns.some(c => c.name === n));
            const dbOrder = db.columns.map(c => c.name).filter(n => repoOrder.includes(n));
            if (repoOrder.join(',') !== dbOrder.join(',')) {
                manual.push(`-- The columns are in another order in the database (${dbOrder.join(', ')}); ALTER TABLE cannot reorder them.`);
            }
        }
    }

    // 3. Constraints and indexes the database lacks.
    const added = repo.constraints
        .filter(c => !db.constraints.some(d => sameConstraint(c, d)))
        .sort((a, b) => ADD_ORDER[a.kind] - ADD_ORDER[b.kind]);
    for (const c of added) {
        if (!c.sql) {
            manual.push(`-- ${describeConstraint(c)} is missing in the database; add it by hand.`);
            continue;
        }
        statements.push(`${alter} ADD ${c.name ? `CONSTRAINT ${quoteIdentifier(c.name)} ` : ''}${c.sql};`);
    }
    for (const index of repo.indexes) {
        if (db.indexes.some(i => indexKeyOf(i) === indexKeyOf(index))) continue;
        if (index.sql) statements.push(`${index.sql.head} ${target}${index.sql.tail ? ` ${index.sql.tail}` : ''};`);
        else manual.push(`-- Index ${index.name} (${indexKeyOf(index)}) is missing in the database; create it by hand.`);
    }

    if (statements.length === 0 && manual.length === 0) {
        lines.push('-- Nothing to change: the table matches the repository.');
    }
    lines.push(...statements);
    if (manual.length > 0) {
        if (statements.length > 0) lines.push('');
        lines.push('-- Not written as statements:', ...manual);
    }
    return `${lines.join('\n')}\n`;
}
